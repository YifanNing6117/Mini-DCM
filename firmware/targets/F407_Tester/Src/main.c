/* USER CODE END Header_StartDefaultTask */
void StartDefaultTask(void const * argument)
{
  /* USER CODE BEGIN 5 */
  /* Infinite loop */
  for(;;)
  {
    /* Event-driven bridge: ISR notification with a 10 ms safety timeout. */
    (void)ulTaskNotifyTake(pdTRUE, pdMS_TO_TICKS(10u));
    Minidcm_AppOnBridgeTaskWakeup();
    Minidcm_AppOnStackHighWaterMark((uint16_t)uxTaskGetStackHighWaterMark((TaskHandle_t)defaultTaskHandle), (uint16_t)uxTaskGetStackHighWaterMark((TaskHandle_t)testerHeartbeatTaskHandle));
    Minidcm_AppPoll();
  }
  /* USER CODE END 5 */
}

